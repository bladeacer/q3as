"""eval_pipeline.py - Run BUILD/TEST/PROVE evaluations and compare base vs fine-tuned models.

Uses the ada-eval framework to run compilation (BUILD), unit test
(TEST), and SPARK proof verification (PROVE) evaluations on code
generated by both the base Qwen3-8B model and the fine-tuned q3as
model. Produces a comparison report showing compilation pass rates,
test pass rates, and SPARK verification success rates.

Generated solutions are consumed in ada-eval's packed form
(outputs/generated_solutions/<model>/<kind>_<dataset>.jsonl), as
written by eval/generate.py.

Usage:
    uv run python eval/eval_pipeline.py
    uv run python eval/eval_pipeline.py --dataset spark_learn --max-samples 20
    uv run python eval/eval_pipeline.py --evals build test prove --jobs 4
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any

# Add ada-eval to Python path (sibling of this project root)
_ADA_EVAL_SRC = Path(__file__).resolve().parents[1].parent / "ada-eval" / "src"
if str(_ADA_EVAL_SRC) not in sys.path:
    sys.path.insert(0, str(_ADA_EVAL_SRC))

# Add scripts/ so the Alire environment helper is importable
_SCRIPTS_DIR = Path(__file__).resolve().parents[1] / "scripts"
if str(_SCRIPTS_DIR) not in sys.path:
    sys.path.insert(0, str(_SCRIPTS_DIR))

from alire_env import has_tool

logger = logging.getLogger("q3as_eval_pipeline")

EVALS_DIR = Path("outputs/eval_results")
GENERATED_DIR = Path("outputs/generated_solutions")

FINE_TUNED_LABEL = "fine_tuned"
DEFAULT_BASE_LABEL = "base_qwen3-8b"


def check_tools_available(evals: list[str]) -> tuple[bool, list[str]]:
    """Check if required tools are available in the Alire environment."""
    tool_map = {
        "build": ["gprbuild", "gnatformat"],
        "test": ["gprbuild", "gprclean"],
        "prove": ["gnatprove", "gprbuild", "gprls"],
    }
    missing: list[str] = []
    for eval_type in evals:
        tools = tool_map.get(eval_type, [])
        for tool in tools:
            if not has_tool(tool):
                missing.append(tool)
    if missing:
        return False, sorted(set(missing))
    return True, []


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run BUILD/TEST/PROVE evaluation on generated Ada code.",
    )
    parser.add_argument(
        "--dataset", type=str, default=None,
        help="Specific dataset to evaluate.",
    )
    parser.add_argument(
        "--max-samples", type=int, default=20,
        help="Maximum samples per dataset.",
    )
    parser.add_argument(
        "--evals", nargs="+", choices=["build", "test", "prove"],
        default=["build", "test", "prove"],
        help="Eval types to run.",
    )
    parser.add_argument(
        "--jobs", type=int, default=1,
        help="Number of parallel evaluation jobs.",
    )
    parser.add_argument(
        "--fine-tuned-label", type=str, default=FINE_TUNED_LABEL,
        help="Generated-solutions directory name for the fine-tuned model.",
    )
    parser.add_argument(
        "--base-label", type=str, default=DEFAULT_BASE_LABEL,
        help="Generated-solutions directory name for the base model.",
    )
    parser.add_argument(
        "--verbose", "-v", action="store_true",
        help="Enable debug logging.",
    )
    return parser.parse_args()


def find_packed_datasets(model_label: str, dataset_filter: str | None) -> list[Path]:
    """Find packed generated datasets (jsonl) for a model label."""
    model_dir = GENERATED_DIR / model_label
    if not model_dir.is_dir():
        logger.warning("No generated datasets for %s at %s", model_label, model_dir)
        return []
    return [
        f for f in sorted(model_dir.glob("*.jsonl"))
        if not dataset_filter or f.stem == f"{f.stem.split('_', 1)[0]}_{dataset_filter}"
        or f.stem == dataset_filter
    ]


def run_ada_eval(
    evals: list[str],
    jobs: int,
    dataset_filter: str | None,
    tools_ok: bool = True,
) -> dict[str, Any]:
    """Run ada-eval framework evaluations on the packed generated datasets."""
    if not tools_ok:
        logger.warning("Required tools not available; skipping ada-eval framework")
        return {}

    from ada_eval.datasets.types import Eval
    from ada_eval.evals import evaluate_directory

    eval_enums = [Eval(e.upper()) for e in evals]

    if not GENERATED_DIR.exists():
        logger.error("No generated solutions found at %s", GENERATED_DIR)
        return {}

    model_labels = sorted(d.name for d in GENERATED_DIR.iterdir() if d.is_dir())
    if not model_labels:
        logger.error("No model directories found in %s", GENERATED_DIR)
        return {}

    results: dict[str, Any] = {}
    for model_label in model_labels:
        for dataset_file in find_packed_datasets(model_label, dataset_filter):
            key = f"{model_label}_{dataset_file.stem}"
            logger.info("Evaluating %s (%s)", key, evals)
            try:
                evaluate_directory(
                    evals=eval_enums,
                    path=dataset_file,
                    output_dir=EVALS_DIR / model_label / dataset_file.stem,
                    jobs=jobs,
                )
                results[key] = {"status": "completed", "evals": evals}
            except Exception as exc:  # noqa: BLE001  (record and continue per dataset)
                logger.error("Evaluation failed for %s: %s", key, exc)
                results[key] = {"status": "failed", "error": str(exc)}

    return results


def compute_stats_from_results(eval_results_dir: Path) -> dict[str, dict[str, int]]:
    """Compute build/test/prove statistics from ada-eval evaluated packed datasets."""
    stats: dict[str, dict[str, int]] = {
        "build": {"compiled": 0, "failed": 0, "total": 0},
        "test": {"passed": 0, "failed": 0, "total": 0},
        "prove": {"proved": 0, "unproved": 0, "error": 0, "total": 0},
    }
    if not eval_results_dir.exists():
        return stats

    for result_file in sorted(eval_results_dir.rglob("*.jsonl")):
        try:
            with open(result_file, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        sample = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    for es in sample.get("evaluation_results", []) or []:
                        kind = es.get("eval")
                        if kind == "build":
                            stats["build"]["total"] += 1
                            if es.get("compiled"):
                                stats["build"]["compiled"] += 1
                            else:
                                stats["build"]["failed"] += 1
                        elif kind == "test":
                            stats["test"]["total"] += 1
                            if es.get("compiled") and es.get("passed_tests"):
                                stats["test"]["passed"] += 1
                            else:
                                stats["test"]["failed"] += 1
                        elif kind == "prove":
                            stats["prove"]["total"] += 1
                            result = es.get("result", "error")
                            if result == "proved":
                                stats["prove"]["proved"] += 1
                            elif result in ("unproved", "proved_incorrectly"):
                                stats["prove"]["unproved"] += 1
                            else:
                                stats["prove"]["error"] += 1
        except OSError as exc:
            logger.warning("Cannot read result file %s: %s", result_file, exc)
    return stats


def rate(block: dict[str, int], numerators: tuple[str, ...]) -> float:
    total = block.get("total", 0)
    if total <= 0:
        return 0.0
    return sum(block.get(n, 0) for n in numerators) / total * 100


def generate_comparison_report(
    results: dict[str, Any],
    fine_tuned_label: str,
    base_label: str,
    output_path: Path,
) -> None:
    """Generate a human-readable comparison report."""
    lines: list[str] = []
    lines.append("=" * 70)
    lines.append("Q3AS EVALUATION REPORT: BASE vs FINE-TUNED MODEL")
    lines.append("=" * 70)

    for model_key in (base_label, fine_tuned_label):
        model_data = results.get(model_key)
        if not model_data:
            lines.append(f"\n--- {model_key} ---")
            lines.append("  (no generated solutions or eval results found)")
            continue
        stats = model_data["stats"]
        lines.append(f"\n--- {model_key} ---")

        b = stats["build"]
        if b["total"]:
            lines.append(
                f"  Compilation: {b['compiled']}/{b['total']} passed "
                f"({b['compiled'] / b['total'] * 100:.1f}%)"
            )
        t = stats["test"]
        if t["total"]:
            lines.append(
                f"  Unit Tests:  {t['passed']}/{t['total']} passed "
                f"({t['passed'] / t['total'] * 100:.1f}%)"
            )
        p = stats["prove"]
        if p["total"]:
            lines.append(
                f"  SPARK Proof: {p['proved']}/{p['total']} proved "
                f"({p['proved'] / p['total'] * 100:.1f}%)"
            )
            lines.append(f"    Unproved: {p['unproved']}, Errors: {p['error']}")

    lines.append(f"\n{'=' * 70}")
    lines.append("COMPARISON SUMMARY")
    lines.append(f"{'=' * 70}")

    base_stats = results.get(base_label, {}).get("stats")
    ft_stats = results.get(fine_tuned_label, {}).get("stats")

    if base_stats and ft_stats:
        lines.append("\nMetric                Base        Fine-tuned   Improvement")
        lines.append("-" * 60)
        for eval_type, numerators in [
            ("build", ("compiled",)),
            ("test", ("passed",)),
            ("prove", ("proved",)),
        ]:
            b_rate = rate(base_stats[eval_type], numerators)
            ft_rate = rate(ft_stats[eval_type], numerators)
            improvement = ft_rate - b_rate
            lines.append(
                f"{eval_type.capitalize():15s}  {b_rate:6.1f}%     {ft_rate:6.1f}%      {improvement:+6.1f}%"
            )
    else:
        lines.append("\nInsufficient data for comparison (need both base and fine-tuned results).")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")

    # Also print to stdout
    print("\n".join(lines))


def main() -> None:
    args = parse_args()
    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")

    logger.info("Starting evaluation pipeline")
    logger.info("Evals: %s", args.evals)
    logger.info("Jobs: %d", args.jobs)
    logger.info("Fine-tuned label: %s | Base label: %s", args.fine_tuned_label, args.base_label)

    # Check tool availability
    tools_ok, missing_tools = check_tools_available(args.evals)
    if not tools_ok:
        logger.warning("Required tools not found in the Alire environment: %s", missing_tools)
        logger.warning("BUILD/TEST/PROVE evaluations require gnatprove, gprbuild, gnatformat")
        logger.warning("Install them via `make prove` (Alire dev workspace build)")

    # Step 1: Run evaluations via ada-eval framework on packed generated datasets
    run_ada_eval(
        evals=args.evals,
        jobs=args.jobs,
        dataset_filter=args.dataset,
        tools_ok=tools_ok,
    )

    # Step 2: Compute statistics for each model from ada-eval result files
    results: dict[str, Any] = {}
    if GENERATED_DIR.exists():
        for model_dir in sorted(GENERATED_DIR.iterdir()):
            if not model_dir.is_dir():
                continue
            results[model_dir.name] = {
                "stats": compute_stats_from_results(EVALS_DIR / model_dir.name)
            }

    if not results:
        empty = {
            "build": {"compiled": 0, "failed": 0, "total": 0},
            "test": {"passed": 0, "failed": 0, "total": 0},
            "prove": {"proved": 0, "unproved": 0, "error": 0, "total": 0},
        }
        results[args.base_label] = {"stats": json.loads(json.dumps(empty))}
        results[args.fine_tuned_label] = {"stats": json.loads(json.dumps(empty))}
        logger.warning("No generated solutions found; wrote placeholder stats only")

    # Step 3: Generate comparison report
    report_path = Path("outputs/comparison_report.txt")
    generate_comparison_report(results, args.fine_tuned_label, args.base_label, report_path)

    # Save JSON results (baseline_eval.py owns outputs/eval_results.json)
    json_results_path = Path("outputs/eval_pipeline_results.json")
    with open(json_results_path, "w") as f:
        json.dump(results, f, indent=2)

    logger.info("Evaluation pipeline complete")


if __name__ == "__main__":
    main()
