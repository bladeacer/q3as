"""eval_pipeline.py - Run BUILD/TEST/PROVE evaluations and compare base vs fine-tuned models.

Uses the ada-eval framework to run compilation (BUILD), unit test
(TEST), and SPARK proof verification (PROVE) evaluations on code
generated by both the base Qwen3-8B model and the fine-tuned q3as
model. Produces a comparison report showing compilation pass rates,
test pass rates, and SPARK verification success rates.

Usage:
    uv run python eval/eval_pipeline.py
    uv run python eval/eval_pipeline.py --dataset spark_learn --max-samples 20
    uv run python eval/eval_pipeline.py --evals build test prove --jobs 4
"""

from __future__ import annotations

import argparse
import shutil
import json
import logging
import sys
from collections import Counter
from pathlib import Path
from typing import Any

# Add ada-eval to Python path (relative to this project root)
_ADA_EVAL_SRC = Path(__file__).resolve().parents[1] / "ada-eval" / "src"
if str(_ADA_EVAL_SRC) not in sys.path:
    sys.path.insert(0, str(_ADA_EVAL_SRC))

logger = logging.getLogger("q3as_eval_pipeline")

EVALS_DIR = Path("outputs/eval_results")
GENERATED_DIR = Path("outputs/generated_solutions")


def check_tools_available(evals: list[str]) -> tuple[bool, list[str]]:
    """Check if required tools are available on the system."""
    tool_map = {
        "build": ["gprbuild", "gnatformat"],
        "test": ["gprbuild", "gprclean"],
        "prove": ["gnatprove", "gprbuild", "gprls"],
    }
    missing: list[str] = []
    for eval_type in evals:
        tools = tool_map.get(eval_type, [])
        for tool in tools:
            if shutil.which(tool) is None:
                missing.append(tool)
    if missing:
        return False, list(set(missing))
    return True, []


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run BUILD/TEST/PROVE evaluation on generated Ada code.",
    )
    parser.add_argument(
        "--dataset", type=str, default=None,
        help="Specific dataset to evaluate.",
    )
    parser.add_argument(
        "--max-samples", type=int, default=20,
        help="Maximum samples per dataset.",
    )
    parser.add_argument(
        "--evals", nargs="+", choices=["build", "test", "prove"],
        default=["build", "test", "prove"],
        help="Eval types to run.",
    )
    parser.add_argument(
        "--jobs", type=int, default=1,
        help="Number of parallel evaluation jobs.",
    )
    parser.add_argument(
        "--model-name", type=str, default="q3as_fine_tuned",
        help="Name for the fine-tuned model.",
    )
    parser.add_argument(
        "--base-model-name", type=str, default="qwen3_base",
        help="Name for the base model.",
    )
    parser.add_argument(
        "--verbose", "-v", action="store_true",
        help="Enable debug logging.",
    )
    return parser.parse_args()


def load_generated_samples(
    dataset_name: str,
    model_label: str,
    max_samples: int,
) -> list[dict[str, Any]]:
    """Load generated samples from the outputs directory."""
    base_dir = Path("outputs/generated_solutions") / model_label
    if not base_dir.exists():
        logger.warning("No generated solutions for %s at %s", model_label, base_dir)
        return []

    dataset_dir = base_dir / dataset_name
    if not dataset_dir.exists():
        # Try to find the dataset directory
        for d in sorted(base_dir.iterdir()):
            if d.is_dir():
                dataset_dir = base_dir / d.name / dataset_name
                if dataset_dir.exists():
                    break
        else:
            logger.warning("Dataset %s not found in %s", dataset_name, base_dir)
            return []

    samples: list[dict[str, Any]] = []
    for sample_dir in sorted(dataset_dir.iterdir()):
        if not sample_dir.is_dir():
            continue
        if sample_dir.name >= max_samples and max_samples > 0 and len(samples) >= max_samples:
            break
        gen_dir = sample_dir / "generated_solution"
        if not gen_dir.exists():
            continue
        prompt_path = sample_dir / "prompt.md"
        prompt = prompt_path.read_text() if prompt_path.exists() else ""
        samples.append({
            "name": sample_dir.name,
            "dir": sample_dir,
            "prompt": prompt,
        })
    return samples[:max_samples]


def run_ada_eval(
    evals: list[str],
    jobs: int,
    dataset_filter: str | None,
    max_samples: int,
    tools_ok: bool = True,
) -> dict[str, Any]:
    """Run ada-eval framework evaluations on generated datasets.

    Uses the ada-eval Python API to load generated datasets and
    run BUILD, TEST, and/or PROVE evaluations.
    """
    if not tools_ok:
        logger.warning("Required tools not available; skipping ada-eval framework")
        return {}

    from ada_eval.datasets.loader import load_datasets
    from ada_eval.datasets.types import Eval
    from ada_eval.evals import evaluate_directory

    eval_enums = [Eval(e.upper()) for e in evals]
    generated_dir = Path("outputs/generated_solutions")

    if not generated_dir.exists():
        logger.error("No generated solutions found at %s", generated_dir)
        return {}

    # Find all dataset directories
    dataset_paths = []
    for model_dir in generated_dir.iterdir():
        if not model_dir.is_dir():
            continue
        for dataset_dir in model_dir.iterdir():
            if not dataset_dir.is_dir():
                continue
            if dataset_filter and dataset_dir.name != dataset_filter:
                continue
            # Check if it has generated_solution subdirs
            has_samples = any(
                (dataset_dir / s / "generated_solution").is_dir()
                for s in dataset_dir.iterdir() if s.is_dir()
            )
            if has_samples:
                dataset_paths.append(dataset_dir)

    if not dataset_paths:
        logger.error("No datasets with generated solutions found")
        return {}

    logger.info("Found %d datasets to evaluate", len(dataset_paths))

    results: dict[str, Any] = {}
    for dataset_dir in dataset_paths:
        model_label = dataset_dir.parent.name
        dataset_name = dataset_dir.name
        key = f"{model_label}_{dataset_name}"
        logger.info("Evaluating %s (%s)", key, evals)

        try:
            evaluate_directory(
                evals=eval_enums,
                path=dataset_dir,
                output_dir=EVALS_DIR / key,
                jobs=jobs,
            )
            results[key] = {"status": "completed", "evals": evals}
        except Exception as exc:
            logger.error("Evaluation failed for %s: %s", key, exc)
            results[key] = {"status": "failed", "error": str(exc)}

    return results


def compute_compilation_stats(eval_results_dir: Path) -> dict[str, int]:
    """Compute compilation statistics from evaluation results."""
    stats = {"compiled": 0, "failed": 0, "total": 0}
    if not eval_results_dir.exists():
        return stats

    for sample_dir in eval_results_dir.iterdir():
        if not sample_dir.is_dir():
            continue
        for result_file in sample_dir.rglob("*.json"):
            try:
                with open(result_file) as f:
                    data = json.load(f)
                # Look for build evaluation stats
                if isinstance(data, dict) and "eval" in data:
                    if data["eval"] == "build":
                        stats["total"] += 1
                        if data.get("compiled"):
                            stats["compiled"] += 1
                        else:
                            stats["failed"] += 1
            except (json.JSONDecodeError, OSError):
                continue
    return stats


def compute_prove_stats(eval_results_dir: Path) -> dict[str, int]:
    """Compute SPARK proof verification statistics."""
    stats = {"proved": 0, "unproved": 0, "error": 0, "total": 0}
    if not eval_results_dir.exists():
        return stats

    for sample_dir in eval_results_dir.iterdir():
        if not sample_dir.is_dir():
            continue
        for result_file in sample_dir.rglob("*.json"):
            try:
                with open(result_file) as f:
                    data = json.load(f)
                if isinstance(data, dict) and data.get("eval") == "prove":
                    stats["total"] += 1
                    result = data.get("result", "")
                    if result == "proved":
                        stats["proved"] += 1
                    elif result == "unproved":
                        stats["unproved"] += 1
                    else:
                        stats["error"] += 1
            except (json.JSONDecodeError, OSError):
                continue
    return stats


def compute_test_stats(eval_results_dir: Path) -> dict[str, int]:
    """Compute test statistics from evaluation results."""
    stats = {"passed": 0, "failed": 0, "total": 0}
    if not eval_results_dir.exists():
        return stats

    for sample_dir in eval_results_dir.iterdir():
        if not sample_dir.is_dir():
            continue
        for result_file in sample_dir.rglob("*.json"):
            try:
                with open(result_file) as f:
                    data = json.load(f)
                if isinstance(data, dict) and data.get("eval") == "test":
                    stats["total"] += 1
                    if data.get("passed_tests"):
                        stats["passed"] += 1
                    else:
                        stats["failed"] += 1
            except (json.JSONDecodeError, OSError):
                continue
    return stats


def generate_comparison_report(
    results: dict[str, Any],
    output_path: Path,
) -> None:
    """Generate a human-readable comparison report."""
    lines: list[str] = []
    lines.append("=" * 70)
    lines.append("Q3AS EVALUATION REPORT: BASE vs FINE-TUNED MODEL")
    lines.append("=" * 70)

    for model_key, model_data in results.items():
        if "stats" not in model_data:
            continue
        stats = model_data["stats"]
        lines.append(f"\n--- {model_key} ---")

        if "build" in stats:
            b = stats["build"]
            compile_rate = (b.get("compiled", 0) / max(b.get("total", 1), 1)) * 100
            lines.append(f"  Compilation: {b['compiled']}/{b['total']} passed ({compile_rate:.1f}%)")

        if "test" in stats:
            t = stats["test"]
            test_rate = (t.get("passed", 0) / max(t.get("total", 1), 1)) * 100
            lines.append(f"  Unit Tests:  {t['passed']}/{t['total']} passed ({test_rate:.1f}%)")

        if "prove" in stats:
            p = stats["prove"]
            prove_rate = (p.get("proved", 0) / max(p.get("total", 1), 1)) * 100
            lines.append(f"  SPARK Proof: {p['proved']}/{p['total']} proved ({prove_rate:.1f}%)")
            lines.append(f"    Unproved: {p['unproved']}, Errors: {p['error']}")

    # Comparison summary
    lines.append(f"\n{'=' * 70}")
    lines.append("COMPARISON SUMMARY")
    lines.append(f"{'=' * 70}")

    # Find base and fine-tuned stats
    base_stats = None
    ft_stats = None
    for model_key, model_data in results.items():
        if "base" in model_key.lower() or "qwen3" in model_key.lower():
            base_stats = model_data.get("stats")
        elif "fine_tuned" in model_key.lower() or "q3as" in model_key.lower():
            ft_stats = model_data.get("stats")

    if base_stats and ft_stats:
        lines.append("\nMetric                Base        Fine-tuned   Improvement")
        lines.append("-" * 60)

        for eval_type in ["build", "test", "prove"]:
            if eval_type in base_stats and eval_type in ft_stats:
                b_rate = base_stats[eval_type].get("passed", 0) / max(base_stats[eval_type].get("total", 1), 1) * 100
                ft_rate = ft_stats[eval_type].get("passed", 0) / max(ft_stats[eval_type].get("total", 1), 1) * 100
                improvement = ft_rate - b_rate
                lines.append(f"{eval_type.capitalize():15s}  {b_rate:6.1f}%     {ft_rate:6.1f}%      {improvement:+6.1f}%")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w") as f:
        f.write("\n".join(lines) + "\n")

    # Also print to stdout
    print("\n".join(lines))


def main() -> None:
    args = parse_args()
    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")

    logger.info("Starting evaluation pipeline")
    logger.info("Evals: %s", args.evals)
    logger.info("Jobs: %d", args.jobs)
    logger.info("Max samples: %d", args.max_samples)

    # Check tool availability
    tools_ok, missing_tools = check_tools_available(args.evals)
    if not tools_ok:
        logger.warning("Required tools not found: %s", missing_tools)
        logger.warning("BUILD/TEST/PROVE evaluations require gnatprove, gprbuild, gnatformat")
        logger.warning("Install GNAT Pro or GNAT Community to enable these evaluations")

    # Step 1: Run evaluations via ada-eval framework
    eval_results = run_ada_eval(
        evals=args.evals,
        jobs=args.jobs,
        dataset_filter=args.dataset,
        max_samples=args.max_samples,
        tools_ok=tools_ok,
    )

    # Step 2: Compute statistics for each model
    results: dict[str, Any] = {}

    if not GENERATED_DIR.exists():
        logger.warning("No generated solutions found at %s", GENERATED_DIR)
        logger.info("Creating a summary report with available metrics only")

    if GENERATED_DIR.exists():
        for model_dir in sorted(GENERATED_DIR.iterdir()):
            if not model_dir.is_dir():
                continue
            model_label = model_dir.name
            model_results = {"stats": {}}

            build_stat = {"compiled": 0, "failed": 0, "total": 0}
            test_stat = {"passed": 0, "failed": 0, "total": 0}
            prove_stat = {"proved": 0, "unproved": 0, "error": 0, "total": 0}

            for dataset_dir in model_dir.iterdir():
                if not dataset_dir.is_dir():
                    continue
                eval_dir = EVALS_DIR / f"{model_label}_{dataset_dir.name}"

                b = compute_compilation_stats(eval_dir)
                build_stat["compiled"] += b.get("compiled", 0)
                build_stat["failed"] += b.get("failed", 0)
                build_stat["total"] += b.get("total", 0)

                t = compute_test_stats(eval_dir)
                test_stat["passed"] += t.get("passed", 0)
                test_stat["failed"] += t.get("failed", 0)
                test_stat["total"] += t.get("total", 0)

                p = compute_prove_stats(eval_dir)
                prove_stat["proved"] += p.get("proved", 0)
                prove_stat["unproved"] += p.get("unproved", 0)
                prove_stat["error"] += p.get("error", 0)
                prove_stat["total"] += p.get("total", 0)

            model_results["stats"] = {
                "build": build_stat,
                "test": test_stat,
                "prove": prove_stat,
            }
            results[model_label] = model_results
    else:
        logger.warning("No generated solutions found; skipping model stats computation")

    # Add placeholder stats if no evaluation results exist
    if not results:
        results["base_model"] = {"stats": {"build": {"compiled": 0, "failed": 0, "total": 0}, "test": {"passed": 0, "failed": 0, "total": 0}, "prove": {"proved": 0, "unproved": 0, "error": 0, "total": 0}}}
        results["q3as_fine_tuned"] = {"stats": {"build": {"compiled": 0, "failed": 0, "total": 0}, "test": {"passed": 0, "failed": 0, "total": 0}, "prove": {"proved": 0, "unproved": 0, "error": 0, "total": 0}}}

    # Step 3: Generate comparison report
    report_path = Path("outputs/eval_results/comparison_report.txt")
    generate_comparison_report(results, report_path)

    # Save JSON results
    json_results_path = Path("outputs/eval_results/results.json")
    with open(json_results_path, "w") as f:
        json.dump(results, f, indent=2)

    logger.info("Evaluation pipeline complete")


if __name__ == "__main__":
    main()
